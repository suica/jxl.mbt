import sys, os
out = ['// Generated by scratch-coding/rec: entropy decoder operations recorded while',
       '// upstream jxl-oxide (patched jxl-coding) decoded real files.',
       '// S sid pad hex | P id sid rel num_dist rel_after | B id sid rel ok rel_after',
       '// R id sid rel kind cluster mult result rel_after | C src dst | F id ok',
       '', '///|', 'let replay_logs : Array[(String, String)] = [']
for path in sys.argv[1:]:
    name = os.path.basename(path)[:-4]
    out.append('  (')
    out.append(f'    "{name}",')
    out.append('    (')
    for line in open(path).read().splitlines():
        out.append('      #|' + line)
    out.append('    ),')
    out.append('  ),')
out.append(']')
print('\n'.join(out))
