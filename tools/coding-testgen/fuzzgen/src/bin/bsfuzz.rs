// Differential cases for jxl-bitstream's Bitstream: random operation
// sequences (continuing after errors) on short random buffers.
use jxl_bitstream::{Bitstream, Error, U};

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 16) as u32
    }
}

fn code(e: &Error) -> u32 {
    match e {
        Error::Io(_) => 0xdead0001,
        Error::NonZeroPadding => 0xdead0002,
        Error::InvalidFloat => 0xdead0003,
        Error::InvalidEnum { value, .. } => 0xdead1000 + value,
        _ => 0xdead0099,
    }
}

fn main() {
    let mut rng = Rng(777);
    println!("// Generated by tools/coding-testgen/fuzzgen (bin bsfuzz) from upstream jxl-bitstream.");
    println!("// (input hex, op seed, log length, FNV-1a hash of log)");
    println!();
    println!("///|");
    println!("let bs_fuzz_cases : Array[(String, UInt, Int, UInt64)] = [");
    for _ in 0..300 {
        let len = rng.next() as usize % 40;
        let bytes: Vec<u8> = (0..len).map(|_| rng.next() as u8).collect();
        let seed = rng.next();
        let mut r = Rng(seed as u64 | 1);
        let mut bs = Bitstream::new(&bytes);
        let mut log: Vec<u32> = Vec::new();
        for _ in 0..60 {
            let op = r.next() % 10;
            let res: Result<u32, Error> = match op {
                0 => { let n = (r.next() % 33) as usize; bs.read_bits(n) }
                1 => { let n = (r.next() % 100) as usize; bs.skip_bits(n).map(|_| 0) }
                2 => { let n = (r.next() % 33) as usize; Ok(bs.peek_bits(n)) }
                3 => { let n = (r.next() % 33) as usize; Ok(bs.peek_bits_prefilled(n)) }
                4 => { let n = (r.next() % 70) as usize; bs.consume_bits(n).map(|_| 0) }
                5 => bs.read_u32(1, U(2), 3 + U(4), 19 + U(8)),
                6 => bs.read_u64().map(|v| (v as u32) ^ ((v >> 32) as u32)),
                7 => bs.read_f16_as_f32().map(|f| f.to_bits()),
                8 => bs.zero_pad_to_byte().map(|_| 0),
                _ => bs.read_bool().map(|b| b as u32),
            };
            log.push(op);
            match res {
                Ok(v) => log.push(v),
                Err(e) => log.push(code(&e)),
            }
            log.push(bs.num_read_bits() as u32);
        }
        let mut h: u64 = 0xcbf29ce484222325;
        for &v in &log {
            for i in 0..4 {
                h ^= ((v >> (8 * i)) & 0xff) as u64;
                h = h.wrapping_mul(0x100000001b3);
            }
        }
        let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
        println!("  (\"{hex}\", {seed}U, {}, 0x{h:016x}UL),", log.len());
    }
    println!("]");
}
